import { defineConfig, devices } from '@playwright/test'

// Сквозной набор на сценарии оформления. Он идёт отдельной проверкой рядом с
// `npm test`, поэтому `npm test` остаётся
// `vitest run` и браузер не тянет: vitest ищет тесты только внутри `src/` и
// только с суффиксом `.test.ts`, Playwright только внутри `e2e/` и только с
// суффиксом `.spec.ts`. Разные каталоги и разные суффиксы, пересечься двум
// наборам негде.

/** Порт отдельный от 3000: иначе прогон попадёт на открытый рядом `next dev`
 *  из другого клона и проверит чужой код. */
const PORT = 3100

const BASE_URL = `http://127.0.0.1:${PORT}`

export default defineConfig({
  testDir: './e2e',
  testMatch: '**/*.spec.ts',

  /**
   * Прогон строго последовательный. Остаток свободных мест и счётчик номеров
   * заказа живут в памяти процесса сервера и общие на весь прогон:
   * параллельные тесты растащили бы их друг у друга. Сброс остатка перед
   * каждым тестом (`e2e/fixtures.ts`) снимает зависимость от порядка, но
   * только при одном работнике.
   */
  workers: 1,
  fullyParallel: false,

  /** Падение набора это дефект, а не повод прогнать ещё раз: повторы прячут
   *  неустойчивый тест вместо того, чтобы его показать. */
  retries: 0,
  /** `test.only` закрывает весь остальной набор, а поймать это некому: CI в
   *  проекте нет. Пусть падает прогон, а не проверка. */
  forbidOnly: true,
  reporter: 'list',

  timeout: 60_000,
  expect: { timeout: 10_000 },

  use: {
    baseURL: BASE_URL,
    /** Трассировка только на падении: `on-first-retry` при `retries: 0` не
     *  записала бы ничего никогда. */
    trace: 'retain-on-failure',
    actionTimeout: 15_000,
  },

  projects: [
    {
      name: 'desktop',
      use: { ...devices['Desktop Chrome'], viewport: { width: 1280, height: 800 } },
      testIgnore: '**/*.mobile.spec.ts',
    },
    {
      name: 'mobile',
      use: { ...devices['Desktop Chrome'], viewport: { width: 360, height: 800 } },
      testMatch: '**/*.mobile.spec.ts',
    },
  ],

  /**
   * Под тестами стоит production-сборка, а не `next dev`: проверяется то, что
   * уходит в поставку, и у страницы нет компиляции на первый переход, от
   * которой падения приходят по таймауту, а не по делу. Поведение, которое
   * есть только в режиме разработки (двойной прогон эффектов в строгом
   * режиме), этим набором не закрыто и остаётся за проверкой в браузере.
   *
   * Ожидание висит на маршруте остатка, а не на странице: маршрут отвечает
   * ровно тогда, когда сервер готов отдавать и то, и другое.
   */
  webServer: {
    command: `npm run build && npm run start -- --port ${PORT}`,
    url: `${BASE_URL}/api/availability`,
    timeout: 180_000,
    reuseExistingServer: !process.env.CI,
    stdout: 'pipe',
  },
})
